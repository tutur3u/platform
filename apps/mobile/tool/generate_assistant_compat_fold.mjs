#!/usr/bin/env node
// Derives the compatibility fold and mark-stripping tables for Mira
// screen-context redaction from the supported ranges in
// assistant_secret_normalize.dart, using the runtime's NFKC and NFD. Run with `node tool/generate_assistant_compat_fold.mjs` from
// apps/mobile after changing the ranges; `--check` fails when the committed
// table is stale. Unicode's normalization stability policy keeps existing
// mappings fixed, so a newer runtime can only add entries.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const bridge = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'lib/features/assistant/bridge'
);
const source = readFileSync(
  join(bridge, 'assistant_secret_normalize.dart'),
  'utf8'
);
const block = source
  .split('const _supportedRanges = <(int, int)>[')[1]
  ?.split('];')[0];
if (!block) throw new Error('Supported ranges not found.');
const ranges = [
  ...block.matchAll(/\((0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\)/g),
].map((match) => [Number(match[1]), Number(match[2])]);
if (ranges.length === 0) throw new Error('No supported ranges parsed.');

const backslash = String.fromCharCode(92);
const hex = (codePoint) => codePoint.toString(16).toUpperCase();
const dartString = (text) =>
  `'${[...text]
    .map((character) => {
      const codePoint = character.codePointAt(0);
      const plain =
        codePoint >= 0x20 &&
        codePoint < 0x7f &&
        !["'", '$', backslash].includes(character);
      return plain ? character : `${backslash}u{${hex(codePoint)}}`;
    })
    .join('')}'`;

// Latin letters drawn as a base letter with a stroke, bar, hook, curl or tail
// (and eth), which have no canonical decomposition. Unicode exposes this only
// through character names, which the runtime lacks, so the class is listed
// here and validated below: each must be supported and must not decompose.
const undecomposedBases = {
  A: [0x23a],
  B: [0x181, 0x182, 0x243],
  b: [0x180, 0x183],
  C: [0x187, 0x23b],
  c: [0x188, 0x23c],
  D: [0xd0, 0x110, 0x189, 0x18a, 0x18b],
  d: [0xf0, 0x111, 0x18c, 0x221],
  E: [0x246],
  e: [0x247],
  F: [0x191],
  f: [0x192],
  G: [0x193, 0x1e4],
  g: [0x1e5],
  H: [0x126],
  h: [0x127],
  I: [0x197],
  J: [0x248],
  j: [0x249],
  K: [0x198],
  k: [0x199],
  L: [0x141, 0x23d],
  l: [0x142, 0x19a, 0x234],
  N: [0x19d, 0x220],
  n: [0x19e, 0x235],
  O: [0xd8, 0x19f],
  o: [0xf8],
  P: [0x1a4],
  p: [0x1a5],
  Q: [0x24a],
  q: [0x24b],
  R: [0x24c],
  r: [0x24d],
  s: [0x23f, 0x1e9c, 0x1e9d],
  T: [0x166, 0x1ac, 0x1ae, 0x23e],
  t: [0x167, 0x1ab, 0x1ad, 0x236],
  U: [0x244],
  V: [0x1b2],
  Y: [0x1b3, 0x24e],
  y: [0x1b4, 0x24f],
  Z: [0x1b5, 0x224],
  z: [0x1b6, 0x225, 0x240],
};

const isSupported = (codePoint) =>
  ranges.some(([start, end]) => codePoint >= start && codePoint <= end);
const undecomposed = new Map();
for (const [base, codePoints] of Object.entries(undecomposedBases)) {
  for (const codePoint of codePoints) {
    const character = String.fromCodePoint(codePoint);
    if (
      !isSupported(codePoint) ||
      character.normalize('NFD') !== character ||
      character.normalize('NFKC') !== character ||
      undecomposed.has(codePoint)
    ) {
      throw new Error(`Invalid undecomposed base U+${hex(codePoint)}.`);
    }
    undecomposed.set(codePoint, base);
  }
}

const entries = [];
const bases = [];
for (const [start, end] of ranges) {
  for (let codePoint = start; codePoint <= end; codePoint++) {
    const character = String.fromCodePoint(codePoint);
    const reading = character.normalize('NFKC');
    if (reading !== character && /[A-Za-z0-9]/.test(reading)) {
      entries.push([codePoint, reading]);
    }
    // Lone marks are removed by the scanner itself; only precomposed
    // characters need a table entry.
    const base =
      undecomposed.get(codePoint) ??
      character.normalize('NFD').replace(/\p{Mn}/gu, '');
    if (base !== character && base !== '') bases.push([codePoint, base]);
  }
}
const table = (rows) =>
  rows
    .map(([codePoint, reading]) => `  0x${hex(codePoint)}: ${dartString(reading)},`)
    .join('\n');

const output = `// GENERATED by tool/generate_assistant_compat_fold.mjs. Do not edit.
//
// Every character in the supported ranges of assistant_secret_normalize.dart
// whose NFKC reading contains an ASCII letter or digit, mapped to that
// reading. Folding them keeps secrets spelled with such characters visible to
// the scanner.

const assistantCompatibilityFolds = <int, String>{
${table(entries)}
};

// Every precomposed character in the supported ranges mapped to its NFD
// decomposition without nonspacing marks, and every stroked, barred or hooked
// Latin letter without a decomposition mapped to its base letter, so the
// mark-stripped reading sees the base letters a reader would.

const assistantMarkStrippedBases = <int, String>{
${table(bases)}
};
`;

const target = join(bridge, 'assistant_secret_compat_fold.g.dart');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error(`${target} is stale; regenerate it.`);
    process.exit(1);
  }
  console.log(`ok (${entries.length} folds, ${bases.length} bases)`);
} else {
  writeFileSync(target, output);
  console.log(`${entries.length} folds, ${bases.length} bases`);
}
