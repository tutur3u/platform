#!/usr/bin/env node
// Derives the compatibility fold table for Mira screen-context redaction from
// the supported ranges in assistant_secret_normalize.dart, using the runtime's
// NFKC. Run with `node tool/generate_assistant_compat_fold.mjs` from
// apps/mobile after changing the ranges; `--check` fails when the committed
// table is stale. Unicode's normalization stability policy keeps existing
// mappings fixed, so a newer runtime can only add entries.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const bridge = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'lib/features/assistant/bridge'
);
const source = readFileSync(
  join(bridge, 'assistant_secret_normalize.dart'),
  'utf8'
);
const block = source
  .split('const _supportedRanges = <(int, int)>[')[1]
  ?.split('];')[0];
if (!block) throw new Error('Supported ranges not found.');
const ranges = [
  ...block.matchAll(/\((0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\)/g),
].map((match) => [Number(match[1]), Number(match[2])]);
if (ranges.length === 0) throw new Error('No supported ranges parsed.');

const backslash = String.fromCharCode(92);
const hex = (codePoint) => codePoint.toString(16).toUpperCase();
const dartString = (text) =>
  `'${[...text]
    .map((character) => {
      const codePoint = character.codePointAt(0);
      const plain =
        codePoint >= 0x20 &&
        codePoint < 0x7f &&
        !["'", '$', backslash].includes(character);
      return plain ? character : `${backslash}u{${hex(codePoint)}}`;
    })
    .join('')}'`;

const entries = [];
for (const [start, end] of ranges) {
  for (let codePoint = start; codePoint <= end; codePoint++) {
    const character = String.fromCodePoint(codePoint);
    const reading = character.normalize('NFKC');
    if (reading !== character && /[A-Za-z0-9]/.test(reading)) {
      entries.push([codePoint, reading]);
    }
  }
}

const output = `// GENERATED by tool/generate_assistant_compat_fold.mjs. Do not edit.
//
// Every character in the supported ranges of assistant_secret_normalize.dart
// whose NFKC reading contains an ASCII letter or digit, mapped to that
// reading. Folding them keeps secrets spelled with such characters visible to
// the scanner.

const assistantCompatibilityFolds = <int, String>{
${entries
  .map(([codePoint, reading]) => `  0x${hex(codePoint)}: ${dartString(reading)},`)
  .join('\n')}
};
`;

const target = join(bridge, 'assistant_secret_compat_fold.g.dart');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error(`${target} is stale; regenerate it.`);
    process.exit(1);
  }
  console.log(`ok (${entries.length} folds)`);
} else {
  writeFileSync(target, output);
  console.log(`${entries.length} folds`);
}
