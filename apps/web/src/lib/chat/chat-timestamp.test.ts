import { describe, expect, it } from 'vitest';
import { normalizeChatTimestamp } from './chat-timestamp';

describe('canonical SQL chat receipt timestamp boundary', () => {
  it.each([
    ['2026-10-18 00:00:00+00', '2026-10-18T00:00:00.000Z'],
    ['2026-10-18 00:00:00.123456+00', '2026-10-18T00:00:00.123456Z'],
    ['2026-10-18 00:15:00.000001+0530', '2026-10-17T18:45:00.000001Z'],
    ['2026-10-18 00:15:00.000001+05:30', '2026-10-17T18:45:00.000001Z'],
    ['2026-10-18 23:45:00-03', '2026-10-19T02:45:00.000Z'],
    ['2024-02-29 23:59:59.1+00', '2024-02-29T23:59:59.1Z'],
    ['2026-10-18T00:00:00.123Z', '2026-10-18T00:00:00.123Z'],
  ])(
    'validates and normalizes %s without losing precision',
    (input, expected) => {
      expect(normalizeChatTimestamp(input)).toBe(expected);
    }
  );
  it.each([
    null,
    42,
    '',
    'infinity',
    '2026-02-29 00:00:00+00',
    '2026-04-31 00:00:00+00',
    '2026-13-01 00:00:00+00',
    '2026-00-01 00:00:00+00',
    '2026-01-00 00:00:00+00',
    '2026-10-18 24:00:00+00',
    '2026-10-18 00:60:00+00',
    '2026-10-18 00:00:60+00',
    '2026-10-18 00:00:00+24',
    '2026-10-18 00:00:00+0060',
    '2026-10-18 00:00:00+00:60',
    '2026-10-18 00:00:00',
    '2026-10-18 00:00:00.UTC',
    '2026-10-18 00:00:00.1234567+00',
    '2026-10-18 00:00:00.+00',
    '2026-10-18 00:00:00+0',
    '2026-10-18 00:00:00+00junk',
    '0001-01-01 00:00:00+01',
  ])('rejects malformed calendar, timezone or fraction %s', (input) => {
    expect(() => normalizeChatTimestamp(input)).toThrow(
      'Invalid chat receipt timestamp'
    );
  });
});
