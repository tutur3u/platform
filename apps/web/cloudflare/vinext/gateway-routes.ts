// Gateway route table for the vinext family Workers.
//
//   bun cloudflare/vinext/gateway-routes.ts           writes the table
//   bun cloudflare/vinext/gateway-routes.ts --check   fails when it is stale
//
// Every app route entry becomes a URL pattern owned by the family whose
// pruned build keeps it. apps/gateway matches request paths against these
// patterns with Next.js precedence and sends unmatched paths to the
// `fallback` family, so no Web path depends on WEB_ORIGIN.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFamilies, PROBE_ENTRIES, routePathFor } from '../opennext/prune';
import { loadVinextFamilies, planVinextPrune } from './prune';

export const GATEWAY_ROUTES_FILE = fileURLToPath(
  new URL('../../../gateway/src/web-routes.generated.json', import.meta.url)
);

/** Gateway dispatch order: the deny-list family first, the catch-all last. */
export const FAMILY_ORDER = [
  'api-ops',
  'api-core',
  'public-auth',
  'dashboard-apps',
  'dashboard',
  'web-rest',
];

export interface GatewayFamily {
  id: string;
  binding: string;
  /** Client asset base; the family serves `<assetPrefix>/_next/static/*`. */
  assetPrefix: string;
}

export interface GatewayRoute {
  family: string;
  /** Also matches behind a leading `/<locale>` segment. */
  localized: boolean;
  /** `/`-separated segments; `[x]`, `[...x]` and `[[...x]]` as in Next.js. */
  pattern: string;
}

export interface GatewayRouteTable {
  note: string;
  fallback: string;
  families: GatewayFamily[];
  routes: GatewayRoute[];
}

export function familyBinding(id: string) {
  return `WEB_FAMILY_${id.toUpperCase().replaceAll('-', '_')}`;
}

export function familyAssetPrefix(id: string) {
  return `/_f/${id}`;
}

/** URL pattern an app entry serves, or null when it serves no URL. */
export function entryPattern(rel: string) {
  const routePath = routePathFor(rel);
  if (routePath === null) return null;
  const base = path.posix.basename(rel);
  const name = base.replace(/\.[a-z]+$/u, '');
  const dir = routePath === '/' ? '' : routePath;
  switch (name) {
    case 'page':
    case 'route':
      return routePath;
    case 'sitemap':
      return `${dir}/sitemap.xml`;
    case 'robots':
      return `${dir}/robots.txt`;
    case 'manifest':
      return `${dir}/manifest.webmanifest`;
    default:
      // Static metadata files keep their file name; generated images may
      // carry an id segment (`opengraph-image/<id>`).
      return /\.(?:png|jpe?g|gif|svg|ico)$/u.test(base)
        ? `${dir}/${base}`
        : `${dir}/${name}/[[...metadata]]`;
  }
}

export function buildGatewayRouteTable(): GatewayRouteTable {
  const { config } = loadVinextFamilies();
  const enabled = config.families.filter((family) => family.enabled);
  const ids = enabled.map((family) => family.id);
  if (
    JSON.stringify([...ids].sort()) !== JSON.stringify([...FAMILY_ORDER].sort())
  ) {
    throw new Error(
      `Gateway family order ${FAMILY_ORDER.join(',')} does not match the enabled families ${ids.join(',')}`
    );
  }
  const fallback = enabled.find((family) => family.rest);
  if (!fallback) throw new Error('No catch-all (rest) family is enabled');
  const routes: GatewayRoute[] = [];
  const seen = new Set<string>();
  for (const id of FAMILY_ORDER) {
    for (const rel of planVinextPrune(id).keep) {
      // Every family keeps the build probe; it belongs to the API family.
      if (PROBE_ENTRIES.includes(rel) && id !== 'api-core') continue;
      const routePath = entryPattern(rel);
      if (routePath === null) continue;
      const localized = routePath.startsWith('/[locale]');
      const pattern = localized
        ? routePath.slice('/[locale]'.length) || '/'
        : routePath;
      const key = `${localized}:${pattern}`;
      if (seen.has(key)) continue;
      seen.add(key);
      routes.push({ family: id, localized, pattern });
    }
  }
  // Unlisted paths under a family's prefixes (and, for the deny-list family,
  // under the deny list) stay with that family, below every route entry.
  const { deny } = loadFamilies().config;
  for (const id of FAMILY_ORDER) {
    const family = enabled.find((candidate) => candidate.id === id);
    if (!family || family.rest) continue;
    const subtrees = family.ownsDenied
      ? deny.filter((entry) => entry.startsWith('/api/'))
      : family.prefix.map((prefix) => prefix.replace(/\/$/u, ''));
    for (const subtree of subtrees) {
      const localized = family.localized && !family.ownsDenied;
      const pattern = `${subtree}/[[...rest]]`;
      const key = `${localized}:${pattern}`;
      if (seen.has(key)) continue;
      seen.add(key);
      routes.push({ family: id, localized, pattern });
    }
  }
  return {
    note: 'Generated by apps/web/cloudflare/vinext/gateway-routes.ts from apps/web/cloudflare/vinext/families.json and the app route entries. Do not edit.',
    fallback: fallback.id,
    families: FAMILY_ORDER.map((id) => ({
      id,
      binding: familyBinding(id),
      assetPrefix: familyAssetPrefix(id),
    })),
    routes,
  };
}

function main(argv: string[]) {
  const text = `${JSON.stringify(buildGatewayRouteTable(), null, 2)}\n`;
  if (argv[0] === '--check') {
    let current = '';
    try {
      current = readFileSync(GATEWAY_ROUTES_FILE, 'utf8');
    } catch {}
    if (current !== text) {
      console.error(
        'apps/gateway/src/web-routes.generated.json is stale; run bun apps/web/cloudflare/vinext/gateway-routes.ts'
      );
      return 1;
    }
    return 0;
  }
  writeFileSync(GATEWAY_ROUTES_FILE, text);
  return 0;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  process.exitCode = main(process.argv.slice(2));
}
