// Service worker for one apps/web vinext family Worker build.
//
//   bun cloudflare/vinext/service-worker.ts <family>           dry run
//   bun cloudflare/vinext/service-worker.ts <family> --apply   writes the route
//
// The Next.js `/serwist/[path]` route bundles src/app/sw.ts with esbuild-wasm
// and reads the revision through node:child_process at prerender time; neither
// runs in a Worker. When the family keeps that route, --apply bundles the
// worker with the same config and replaces the route with one that serves the
// prebuilt files. It runs after prune.ts --apply and before `vp build`, only
// in a disposable checkout.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildOfflineWorker,
  type OfflineWorkerFile,
} from '@tuturuuu/offline/route';
import { WEB_OFFLINE_WORKER_CONFIG } from '../../src/lib/offline-worker-config';
import {
  DEFAULT_APP_DIR,
  DISPOSABLE_MARKER,
  DISPOSABLE_MARKER_CONTENT,
} from '../opennext/prune';
import { planVinextPrune } from './prune';

/** The service-worker route entry, relative to src/app. */
export const OFFLINE_ROUTE_ENTRY = 'serwist/[path]/route.ts';
/** The prebuilt files module written beside the route. */
export const OFFLINE_FILES_MODULE =
  'serwist/[path]/offline-worker.generated.ts';

export const PREBUILT_ROUTE_SOURCE = `import { createPrebuiltOfflineRoute } from '@tuturuuu/offline/route/prebuilt';
import { OFFLINE_WORKER_FILES } from './offline-worker.generated';

export const { GET, generateStaticParams } =
  createPrebuiltOfflineRoute(OFFLINE_WORKER_FILES);
`;

export function offlineFilesModuleSource(files: OfflineWorkerFile[]) {
  return `// Generated by cloudflare/vinext/service-worker.ts. Do not edit.
import type { OfflineWorkerFile } from '@tuturuuu/offline/route/prebuilt';

export const OFFLINE_WORKER_FILES: OfflineWorkerFile[] = ${JSON.stringify(files, null, 2)};
`;
}

/** Whether the family build serves the service-worker route. */
export function familyServesOfflineWorker(
  familyId: string,
  appDir = DEFAULT_APP_DIR
) {
  return planVinextPrune(familyId, appDir).keep.includes(OFFLINE_ROUTE_ENTRY);
}

/**
 * Bundles the worker and replaces the route with the prebuilt one. Refuses
 * outside a disposable checkout. Returns the served paths, or null when the
 * family does not own the route.
 */
export async function applyPrebuiltOfflineWorker(
  familyId: string,
  appDir = DEFAULT_APP_DIR,
  build: typeof buildOfflineWorker = buildOfflineWorker
) {
  const marker = path.join(appDir, DISPOSABLE_MARKER);
  if (
    !existsSync(marker) ||
    readFileSync(marker, 'utf8') !== DISPOSABLE_MARKER_CONTENT
  ) {
    throw new Error(
      `Refusing to write the service worker: ${marker} is missing. It runs only in a disposable checkout.`
    );
  }
  if (!familyServesOfflineWorker(familyId, appDir)) return null;
  const { disableInDev: _disableInDev, ...config } = WEB_OFFLINE_WORKER_CONFIG;
  const files = await build(config, appDir);
  if (!files.some((file) => file.path === 'sw.js')) {
    throw new Error('The service worker build emitted no sw.js.');
  }
  const appSrc = path.join(appDir, 'src/app');
  writeFileSync(
    path.join(appSrc, OFFLINE_FILES_MODULE),
    offlineFilesModuleSource(files)
  );
  writeFileSync(path.join(appSrc, OFFLINE_ROUTE_ENTRY), PREBUILT_ROUTE_SOURCE);
  return files.map((file) => file.path);
}

async function main(argv: string[]) {
  const [familyId, flag] = argv;
  if (!familyId || (flag && flag !== '--apply')) {
    console.error('usage: service-worker.ts <family> [--apply]');
    return 2;
  }
  if (flag !== '--apply') {
    console.log(
      familyServesOfflineWorker(familyId)
        ? `${familyId} serves ${OFFLINE_ROUTE_ENTRY}; --apply prebuilds it`
        : `${familyId} does not serve ${OFFLINE_ROUTE_ENTRY}`
    );
    return 0;
  }
  const served = await applyPrebuiltOfflineWorker(familyId);
  console.log(
    served
      ? `prebuilt service worker for ${familyId}: ${served.join(', ')}`
      : `${familyId} does not serve ${OFFLINE_ROUTE_ENTRY}; nothing to prebuild`
  );
  return 0;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (error: unknown) => {
      console.error(error instanceof Error ? error.message : error);
      process.exitCode = 1;
    }
  );
}
