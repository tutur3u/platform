import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { lstatSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const schemaNames = Object.freeze(['public', 'private', 'storage']);
const reviewedCliVersion = '2.117.0';
const failure = () => new Error('Bounded employee type generation failed');
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

/** Capture bounded output; drain diagnostics and the owned process group before resolving. */
export function runTypegenCommand(
  command,
  args,
  cwd,
  { timeoutMs = 300000, maxBytes = 32 * 1024 * 1024, killGraceMs = 1000 } = {}
) {
  return new Promise((resolve, reject) => {
    let child;
    try {
      child = spawn(command, args, {
        cwd,
        detached: true,
        stdio: ['ignore', 'pipe', 'pipe'],
      });
    } catch {
      reject(failure());
      return;
    }
    const chunks = [];
    let bytes = 0;
    let denied = false;
    let forceTimer;
    const signalGroup = (signal) => {
      if (!child.pid) return;
      try {
        process.kill(-child.pid, signal);
      } catch (error) {
        if (error.code !== 'ESRCH') denied = true;
      }
    };
    const terminate = () => {
      denied = true;
      signalGroup('SIGTERM');
      forceTimer ??= setTimeout(() => signalGroup('SIGKILL'), killGraceMs);
    };
    const deadline = setTimeout(terminate, timeoutMs);
    child.stdout.on('data', (chunk) => {
      bytes += chunk.length;
      if (bytes > maxBytes) terminate();
      else if (!denied) chunks.push(chunk);
    });
    child.stderr.resume();
    child.on('error', () => {
      denied = true;
    });
    child.on('close', async (code, signal) => {
      clearTimeout(deadline);
      clearTimeout(forceTimer);
      // A direct child exit is not evidence that its subprocesses have drained.
      const groupExists = () => {
        try {
          if (child.pid) process.kill(-child.pid, 0);
          return Boolean(child.pid);
        } catch (error) {
          return error.code !== 'ESRCH';
        }
      };
      if (groupExists()) {
        denied = true;
        signalGroup('SIGKILL');
        const drainDeadline = Date.now() + 5000;
        while (groupExists() && Date.now() < drainDeadline) {
          await new Promise((drain) => setTimeout(drain, 25));
        }
      }
      if (denied || signal || code !== 0) reject(failure());
      else resolve(Buffer.concat(chunks));
    });
  });
}

/** Hash complete selected schema-source paths and bytes without emitting SQL or fixture contents. */
export function schemaSnapshotHash(repositoryRoot, trackedFiles) {
  const entries = [...trackedFiles].sort().map((file) => {
    if (!file.startsWith('apps/database/supabase/') || file.includes('..')) {
      throw failure();
    }
    return [file, sha256(readFileSync(path.join(repositoryRoot, file)))];
  });
  return sha256(JSON.stringify(entries));
}

/** Generate only local schema definitions; never write generated bytes into selected source. */
export async function generateEmployeeTypes({
  binaryPath,
  metadata,
  receiptDirectory,
  sourceSha,
  controlSha,
  snapshotSha256,
  runner = runTypegenCommand,
}) {
  if (
    !/^[a-f0-9]{40}$/u.test(sourceSha ?? '') ||
    !/^[a-f0-9]{40}$/u.test(controlSha ?? '') ||
    !/^[a-f0-9]{64}$/u.test(snapshotSha256 ?? '') ||
    metadata.headSha !== sourceSha ||
    !/^tt-[a-z0-9-]+-[a-f0-9]{8}-[a-f0-9]{10}$/u.test(metadata.projectId ?? '')
  )
    throw failure();
  const stat = lstatSync(receiptDirectory);
  if (!stat.isDirectory() || stat.isSymbolicLink()) throw failure();
  const version = (
    await runner(binaryPath, ['--version'], metadata.disposableRoot, {
      timeoutMs: 10000,
      maxBytes: 1024,
    })
  )
    .toString('utf8')
    .trim();
  if (version !== reviewedCliVersion) throw failure();
  const contents = await runner(
    binaryPath,
    [
      '--workdir',
      metadata.disposableRoot,
      'gen',
      'types',
      'typescript',
      '--local',
      '--schema',
      schemaNames.join(','),
      '--query-timeout',
      '30s',
    ],
    metadata.disposableRoot
  );
  const text = contents.toString('utf8');
  if (
    !contents.equals(Buffer.from(text)) ||
    !text.trim() ||
    !/^export type Database\s*=\s*\{/mu.test(text) ||
    !schemaNames.every((schema) =>
      new RegExp(`^  ${schema}: \\{`, 'mu').test(text)
    )
  )
    throw failure();
  const artifact = 'generated-types.ts';
  writeFileSync(path.join(receiptDirectory, artifact), contents, {
    flag: 'wx',
    mode: 0o600,
  });
  return {
    version: 1,
    sourceSha,
    controlSha,
    projectId: metadata.projectId,
    snapshotSha256,
    snapshotKind: 'tracked-source-before-isolated-config-rewrite',
    schemas: schemaNames,
    cliVersion: version,
    artifact,
    sha256: sha256(contents),
    bytes: contents.length,
    generated: true,
    consumerQualified: false,
  };
}
