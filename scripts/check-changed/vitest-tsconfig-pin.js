'use strict';

// Oxc tsconfig discovery walks upward past tsconfig files that do not include
// a file (most workspaces exclude their tests). In a standalone checkout the
// walk ends without a match and the transform uses defaults, as in CI. In a
// worktree nested inside another checkout (<checkout>/.worktrees/<name>), the
// walk reaches that checkout's root tsconfig, whose referenced package configs
// cannot resolve @tuturuuu/typescript-config without its node_modules, and
// every such test fails with TSCONFIG_ERROR. For nested worktrees only, run
// Vitest through a generated wrapper config that pins the workspace tsconfig.

const fs = require('node:fs');
const path = require('node:path');

const VITEST_CONFIGS = [
  'vitest.config.ts',
  'vitest.config.mts',
  'vitest.config.mjs',
  'vitest.config.js',
  'vitest.config.cts',
  'vitest.config.cjs',
];
const WRAPPER = '.check-changed.vitest.config.mjs';

/** The nearest tsconfig.json above the repository root, or null. */
function outerTsconfig(root, fsImpl = fs) {
  let dir = path.dirname(path.resolve(root));
  for (;;) {
    const candidate = path.join(dir, 'tsconfig.json');
    if (fsImpl.existsSync(candidate)) return candidate;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function wrapperSource(config, tsconfig) {
  return `// Generated by bun check:changed for a nested worktree; safe to delete.
import { mergeConfig } from 'vitest/config';
import base from ${JSON.stringify(`./${config}`)};

const resolved = typeof base === 'function' ? await base({ command: 'serve', mode: 'test' }) : await base;
export default mergeConfig(resolved, { tsconfig: ${JSON.stringify(tsconfig)} });
`;
}

/**
 * Returns `{ args, cleanup }` for a Vitest step. Outside a nested worktree,
 * or for a workspace without its own Vitest config and tsconfig.json, the
 * arguments are unchanged.
 */
function pinVitestTsconfig(step, root, fsImpl = fs) {
  const unchanged = { args: step.args, cleanup: () => {} };
  if (!String(step.id ?? '').startsWith('vitest:')) return unchanged;
  if (!outerTsconfig(root, fsImpl)) return unchanged;
  const workspace = path.join(root, step.cwd ?? '');
  const config = VITEST_CONFIGS.find((name) =>
    fsImpl.existsSync(path.join(workspace, name))
  );
  const tsconfig = path.join(workspace, 'tsconfig.json');
  if (!config || !fsImpl.existsSync(tsconfig)) return unchanged;
  const wrapper = path.join(workspace, WRAPPER);
  fsImpl.writeFileSync(wrapper, wrapperSource(config, tsconfig));
  return {
    args: [...step.args, '--config', WRAPPER],
    cleanup: () => fsImpl.rmSync(wrapper, { force: true }),
  };
}

module.exports = { WRAPPER, outerTsconfig, pinVitestTsconfig, wrapperSource };
