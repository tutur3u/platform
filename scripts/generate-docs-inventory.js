const fs = require('node:fs');
const path = require('node:path');
const { PAUSED_APP_DIRECTORIES } = require('./paused-runtimes.js');

const ROOT = path.resolve(__dirname, '..');
const GENERATED = 'reference/repository';
const SOURCE = 'https://github.com/tutur3u/platform/blob/main/';
const DEPENDENCY_FIELDS = [
  'dependencies',
  'devDependencies',
  'optionalDependencies',
  'peerDependencies',
];

function walk(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs
    .readdirSync(directory, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name, 'en'))
    .flatMap((entry) => {
      if (
        [
          'node_modules',
          '.next',
          '.git',
          'target',
          'build',
          '.dart_tool',
          'dist',
        ].includes(entry.name)
      )
        return [];
      const file = path.join(directory, entry.name);
      return entry.isDirectory() ? walk(file) : [file];
    });
}

// Bun's text lockfile is JSON with trailing commas. Preserve quoted strings.
function parseLock(source) {
  let quoted = false;
  let escaped = false;
  let clean = '';
  for (let index = 0; index < source.length; index++) {
    const char = source[index];
    if (!quoted && char === ',') {
      let next = index + 1;
      while (/\s/.test(source[next] ?? '') && next < source.length) next++;
      if (source[next] === '}' || source[next] === ']') continue;
    }
    clean += char;
    if (quoted && char === '\\' && !escaped) {
      escaped = true;
      continue;
    }
    if (char === '"' && !escaped) quoted = !quoted;
    escaped = false;
  }
  return JSON.parse(clean);
}

function code(value) {
  return `\`${String(value).replace(/\|/g, '&#124;').replace(/`/g, '')}\``;
}

function sourceLink(file, label = file) {
  return `[${label}](${SOURCE}${file.split('/').map(encodeURIComponent).join('/')})`;
}

function page(title, description, body) {
  return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n{/* Generated by scripts/generate-docs-inventory.js. Do not edit by hand. */}\n\n${body}\n`;
}

function routePath(relative) {
  const segments = relative
    .split('/')
    .slice(0, -1)
    .filter(
      (segment) => !/^\([^)]*\)$/.test(segment) && !segment.startsWith('@')
    );
  return `/${segments.join('/')}`;
}

function collect(root = ROOT) {
  const manifests = [];
  const apps = [];
  for (const base of ['apps', 'packages']) {
    for (const name of fs.readdirSync(path.join(root, base)).sort()) {
      const dir = path.join(root, base, name);
      if (!fs.statSync(dir).isDirectory()) continue;
      if (base === 'apps' && PAUSED_APP_DIRECTORIES.has(name)) {
        apps.push({
          name,
          paused: true,
          next: false,
          manifest: null,
          routes: [],
        });
        continue;
      }
      const file = `${base}/${name}/package.json`;
      const manifest = fs.existsSync(path.join(root, file))
        ? JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'))
        : null;
      if (manifest)
        manifests.push({ directory: `${base}/${name}`, file, manifest });
      if (base !== 'apps') continue;
      const next = fs.existsSync(path.join(dir, 'next.config.ts'));
      const routeRoot = path.join(dir, 'src/app');
      const routes = next
        ? walk(routeRoot)
            .filter((file) => /\/(page|route)\.[jt]sx?$/.test(file))
            .map((file) => {
              const relative = path
                .relative(routeRoot, file)
                .split(path.sep)
                .join('/');
              const api = /\/route\.[jt]sx?$/.test(file);
              const source = fs.readFileSync(file, 'utf8');
              const methods = api
                ? [
                    ...new Set(
                      [
                        ...source.matchAll(
                          /\b(?:GET|POST|PUT|PATCH|DELETE|OPTIONS|HEAD)\b/g
                        ),
                      ].map((match) => match[0])
                    ),
                  ]
                    .sort()
                    .join(', ')
                : 'Page';
              return {
                file: path.relative(root, file).split(path.sep).join('/'),
                pathname: routePath(relative),
                methods: methods || 'See source',
              };
            })
        : [];
      apps.push({ name, next, manifest, routes });
    }
  }
  return { apps, manifests };
}

function outputs(root = ROOT) {
  const files = new Map();
  const { apps, manifests } = collect(root);
  const config = JSON.parse(
    fs.readFileSync(path.join(root, 'package.json'), 'utf8')
  );
  const lock = parseLock(fs.readFileSync(path.join(root, 'bun.lock'), 'utf8'));
  const policy = JSON.parse(
    fs.readFileSync(
      path.join(root, 'packages/utils/src/seo-policy.json'),
      'utf8'
    )
  );
  const lockVersions = new Map();
  for (const record of Object.values(lock.packages)) {
    const specifier = record[0];
    if (typeof specifier !== 'string' || specifier.includes('@workspace:'))
      continue;
    const boundary = specifier.lastIndexOf('@');
    const name = specifier.slice(0, boundary);
    const version = specifier.slice(boundary + 1);
    if (!lockVersions.has(name)) lockVersions.set(name, new Set());
    lockVersions.get(name).add(version);
  }
  const deps = new Map();
  for (const { directory, manifest } of [
    { directory: '.', manifest: config },
    ...manifests,
  ]) {
    for (const field of DEPENDENCY_FIELDS) {
      for (const [name, version] of Object.entries(manifest[field] ?? {})) {
        if (version.startsWith('workspace:')) continue;
        if (!deps.has(name))
          deps.set(name, { ranges: new Set(), owners: new Set() });
        deps.get(name).ranges.add(version);
        deps.get(name).owners.add(directory);
      }
    }
  }

  const runtimeRows = [
    `| Bun | ${code(config.packageManager)} | ${sourceLink('package.json')} |`,
    `| Node.js | ${code(config.engines?.node ?? 'See CI')} | ${sourceLink('package.json')} |`,
  ];
  for (const [file, names] of [
    ['apps/mobile/pubspec.yaml', ['version', 'sdk', 'flutter']],
    ['apps/discord/pyproject.toml', ['version', 'requires-python']],
  ]) {
    const source = fs.readFileSync(path.join(root, file), 'utf8');
    for (const name of names) {
      const match = source.match(
        new RegExp(`^\\s*${name}\\s*[:=]\\s*(.+)$`, 'm')
      );
      if (match)
        runtimeRows.push(
          `| ${file.split('/')[1]} ${name} | ${code(match[1].replace(/"/g, ''))} | ${sourceLink(file)} |`
        );
    }
  }
  const frameworkNames = [
    'next',
    'react',
    'react-dom',
    'typescript',
    'tailwindcss',
    'ai',
    '@tanstack/react-start',
    '@tanstack/react-router',
    '@tanstack/react-query',
    'vite',
    'vitest',
    'turbo',
    '@biomejs/biome',
    'effect',
    'zod',
    'wrangler',
    'supabase',
  ];
  const frameworkRows = frameworkNames
    .filter((name) => deps.has(name))
    .map(
      (name) =>
        `| ${code(name)} | ${[...deps.get(name).ranges].sort().map(code).join(', ')} | ${[...(lockVersions.get(name) ?? [])].sort().map(code).join(', ')} |`
    );
  const dependencyPages = [];
  const sortedDeps = [...deps].sort(([a], [b]) => a.localeCompare(b, 'en'));
  for (let offset = 0; offset < sortedDeps.length; offset += 100) {
    const number = Math.floor(offset / 100) + 1;
    const slug = `${GENERATED}/dependencies-${number}`;
    dependencyPages.push(slug);
    const rows = sortedDeps.slice(offset, offset + 100).map(
      ([name, entry]) =>
        `| ${code(name)} | ${[...entry.ranges].sort().map(code).join(', ')} | ${[...(lockVersions.get(name) ?? [])].sort().map(code).join(', ') || 'Not locked'} | ${[
          ...entry.owners,
        ]
          .sort()
          .map((owner) =>
            sourceLink(`${owner === '.' ? '' : `${owner}/`}package.json`, owner)
          )
          .join(', ')} |`
    );
    files.set(
      `${slug}.mdx`,
      page(
        `Dependency versions ${number}`,
        'Declared dependency ranges, locked resolutions, and owning workspaces.',
        `[Version guide](/${GENERATED}/versions). Locked versions include every resolution of each direct dependency, not just one workspace's resolution. Peer declarations do not necessarily install a package.\n\n| Dependency | Declared ranges | Lockfile resolutions | Declaring workspaces |\n| --- | --- | --- | --- |\n${rows.join('\n')}`
      )
    );
  }
  const nativePages = [];
  for (const [name, file] of [
    ['Python', 'apps/discord/uv.lock'],
    ['Dart', 'apps/mobile/pubspec.lock'],
  ]) {
    const source = fs.readFileSync(path.join(root, file), 'utf8');
    const records =
      name === 'Python'
        ? [
            ...source.matchAll(
              /\[\[package\]\]\nname = "([^"\n]+)"\nversion = "([^"\n]+)"/g
            ),
          ].map((match) => [match[1], match[2]])
        : [
            ...source.matchAll(
              /^ {2}([\w-]+):\n([\s\S]*?)(?=^ {2}[\w-]+:|^sdks:|$(?![\s\S]))/gm
            ),
          ].flatMap((match) => {
            const version = match[2].match(
              /^ {4}version: "?([^"\n]+)"?$/m
            )?.[1];
            return version ? [[match[1], version]] : [];
          });
    records.sort(([a], [b]) => a.localeCompare(b, 'en'));
    if (!records.length)
      throw new Error(`No locked ${name} versions in ${file}`);
    for (let offset = 0; offset < records.length; offset += 100) {
      const number = Math.floor(offset / 100) + 1;
      const slug = `${GENERATED}/${name.toLowerCase()}-dependencies-${number}`;
      nativePages.push(slug);
      files.set(
        `${slug}.mdx`,
        page(
          `${name} locked dependencies ${number}`,
          `Resolved ${name} package versions in the maintained ${file.split('/')[1]} workspace.`,
          `Source: ${sourceLink(file)}. This reference includes direct and transitive lockfile entries; resolution markers, platform constraints, and dependency relationships remain in the owning lockfile. It is not a deployment or upstream-latest claim.\n\n| Package | Locked version |\n| --- | --- |\n${records
            .slice(offset, offset + 100)
            .map(
              ([packageName, version]) =>
                `| ${code(packageName)} | ${code(version)} |`
            )
            .join('\n')}\n\n[Version guide](/${GENERATED}/versions).`
        )
      );
    }
  }
  dependencyPages.push(...nativePages);
  const releaseSource = fs.readFileSync(
    path.join(root, 'packages/utils/src/platform-release.ts'),
    'utf8'
  );
  const platformVersion = releaseSource.match(
    /TUTURUUU_PLATFORM_VERSION = '([^']+)'/
  )?.[1];
  if (platformVersion)
    runtimeRows.push(
      `| Platform release | ${code(platformVersion)} | ${sourceLink('packages/utils/src/platform-release.ts')} |`
    );
  const mintlifyVersion = JSON.parse(
    fs.readFileSync(path.join(root, 'apps/docs/mintlify-version.json'), 'utf8')
  ).version;
  runtimeRows.push(
    `| Mintlify CLI | ${code(mintlifyVersion)} | ${sourceLink('apps/docs/mintlify-version.json')} |`
  );
  files.set(
    `${GENERATED}/versions.mdx`,
    page(
      'Versions and toolchain',
      'Repository runtime pins, framework versions, workspace releases, and dependency references.',
      `This reference reflects the checked-in manifests and lockfile for maintained workspaces. It describes the versions Tuturuuu uses, rather than asserting that every dependency is the newest upstream release. A package range is not a deployed version. Install with the pinned Bun version and ${code('bun install --frozen-lockfile')}; release artifacts and deployment evidence establish what is running. Rust/TanStack Start are paused and excluded from refreshes.\n\n## Runtime pins\n\n| Runtime or package | Declaration | Source |\n| --- | --- | --- |\n${runtimeRows.join('\n')}\n\n## Frameworks and tooling\n\n| Dependency | Declared ranges | Locked resolutions |\n| --- | --- | --- |\n${frameworkRows.join('\n')}\n\n## Complete dependency reference\n\n${dependencyPages.map((slug, index) => `- [${slug.includes('python-') ? 'Python locked dependencies' : slug.includes('dart-') ? 'Dart locked dependencies' : 'npm dependency versions'} ${slug.match(/-(\d+)$/)?.[1] ?? index + 1}](/${slug})`).join('\n')}\n\nPython resolutions live in ${sourceLink('apps/discord/uv.lock')}; Dart resolutions in ${sourceLink('apps/mobile/pubspec.lock')}. Their manifest requirements are separate from npm package ranges.\n\n## Workspace release versions\n\nRelease Please owns version changes; do not manually align independently released packages.\n\n| Workspace | Package | Version |\n| --- | --- | --- |\n${manifests.map(({ directory, file, manifest }) => `| ${sourceLink(file, directory)} | ${code(manifest.name)} | ${code(manifest.version ?? 'Unversioned')} |`).join('\n')}`
    )
  );

  const routePages = [];
  const catalogRows = [];
  for (const app of apps) {
    if (app.paused) {
      catalogRows.push(
        `| ${sourceLink(`apps/${app.name}`, app.name)} | Paused; not in use | Not an active public runtime | [Operating decision](/build/devops/active-runtime) |`
      );
      continue;
    }
    const chunks = Math.max(1, Math.ceil(app.routes.length / 180));
    const references = [];
    for (let number = 1; number <= chunks; number++) {
      const slug = `${GENERATED}/routes/${app.name}${chunks > 1 ? `-${number}` : ''}`;
      routePages.push(slug);
      references.push(
        `[${chunks > 1 ? `Part ${number}` : 'Routes'}](/${slug})`
      );
      const rows = app.routes
        .slice((number - 1) * 180, number * 180)
        .map(
          (route) =>
            `| ${code(route.pathname)} | ${route.methods} | ${sourceLink(route.file, 'Implementation')} |`
        );
      const runtime = app.next
        ? 'Next.js App Router'
        : app.name === 'tanstack-web'
          ? 'TanStack Start migration target'
          : app.name === 'backend'
            ? 'Rust backend migration target'
            : app.name === 'mobile'
              ? 'Flutter'
              : 'Service or supporting workspace';
      files.set(
        `${slug}.mdx`,
        page(
          `${app.name}: routes${chunks > 1 ? ` (${number}/${chunks})` : ''}`,
          `Source entry points and route ownership for the ${app.name} workspace.`,
          `Runtime: **${runtime}**. Source: ${sourceLink(`apps/${app.name}`, `apps/${app.name}`)}.${app.manifest ? ` Package: ${code(app.manifest.name)}.` : ''}\n\nThis inventory lists concrete Next page and handler files, including generated wrappers. Methods are lexical source evidence; consult the implementation for re-exports, authorization, status codes, payloads, and fallbacks. Filesystem presence does not establish public access, deployment, entitlement, or a supported external API contract. Route groups are omitted from URLs; dynamic parameters are shown in brackets.\n\n${rows.length ? `| URL pattern | Page or HTTP methods | Source |\n| --- | --- | --- |\n${rows.join('\n')}` : `This workspace has no Next.js page/handler inventory. Read ${sourceLink(`apps/${app.name}`, 'the owning workspace')} for native, Worker, or infrastructure entry points and the [active runtime map](/build/devops/active-runtime) for operational ownership.`}\n\n[All apps and services](/${GENERATED}/catalog). [Versions](/${GENERATED}/versions).`
        )
      );
    }
    const indexPolicy = policy[app.name];
    catalogRows.push(
      `| ${sourceLink(`apps/${app.name}`, app.name)} | ${app.next ? 'Next.js' : app.name === 'mobile' ? 'Flutter' : app.name === 'backend' ? 'Rust migration' : app.name === 'tanstack-web' ? 'TanStack migration' : 'Service/support'} | ${indexPolicy ? (indexPolicy.publicPaths.length || indexPolicy.publicPatterns.length || app.name === 'web' ? 'Explicit public pages; private routes noindex' : 'Private: noindex') : 'See owning runtime'} | ${references.join(', ')} |`
    );
  }
  files.set(
    `${GENERATED}/catalog.mdx`,
    page(
      'All apps, services, and packages',
      'Complete source-derived index of the Tuturuuu monorepo and its route references.',
      `Use the [product directory](/platform/applications/overview) to learn workflows, and this catalog to locate every implementation workspace. The table includes infrastructure, experiments, and migration targets; inclusion is not a claim of a publicly launched product. External integrations such as [Shiraoki](/platform/applications/shiraoki) can live outside this repository.\n\n## Apps and services\n\n| Workspace | Runtime | Search policy | Route reference |\n| --- | --- | --- | --- |\n${catalogRows.join('\n')}\n\n## Shared packages\n\n| Package | Source | Public exports |\n| --- | --- | --- |\n${manifests
        .filter((entry) => entry.directory.startsWith('packages/'))
        .map(
          ({ directory, file, manifest }) =>
            `| ${code(manifest.name)} | ${sourceLink(file, directory)} | ${
              Object.keys(manifest.exports ?? {})
                .map(code)
                .join(', ') || 'See package manifest'
            } |`
        )
        .join(
          '\n'
        )}\n\nWildcard exports describe supported import families, not every runtime symbol. Read the package's source and tests before extending an integration.`
    )
  );
  return { files, routePages, dependencyPages };
}

function generate({ root = ROOT, check = false } = {}) {
  const { files, routePages, dependencyPages } = outputs(root);
  const configFile = path.join(root, 'apps/docs/docs.json');
  const config = JSON.parse(fs.readFileSync(configFile, 'utf8'));
  const findReference = (value) => {
    if (!value || typeof value !== 'object') return null;
    if (value.group === 'Reference') return value;
    for (const child of Object.values(value)) {
      if (child && typeof child === 'object') {
        const found = findReference(child);
        if (found) return found;
      }
    }
    return null;
  };
  const reference = findReference(config.navigation);
  if (!reference)
    throw new Error('Docs navigation is missing the Reference group');
  const group = {
    group: 'Repository inventory',
    pages: [
      `${GENERATED}/catalog`,
      `${GENERATED}/versions`,
      { group: 'Dependencies', pages: dependencyPages },
      { group: 'Routes by app', pages: routePages },
    ],
  };
  reference.pages = [
    ...reference.pages.filter((entry) => entry?.group !== group.group),
    group,
  ];
  const currentConfig = fs.readFileSync(configFile, 'utf8');
  if (JSON.stringify(JSON.parse(currentConfig)) !== JSON.stringify(config))
    files.set('../docs.json', `${JSON.stringify(config, null, 2)}\n`);
  const stale = [];
  for (const [file, source] of files) {
    const target =
      file === '../docs.json' ? configFile : path.join(root, 'apps/docs', file);
    if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === source)
      continue;
    stale.push(file);
    if (!check) {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, source);
    }
  }
  if (check && stale.length)
    throw new Error(`Stale documentation inventory:\n${stale.join('\n')}`);
  return stale;
}

module.exports = { collect, generate, outputs, parseLock, routePath };
if (require.main === module) {
  const changed = generate({ check: process.argv.includes('--check') });
  console.log(
    `Documentation inventory: ${changed.length} ${process.argv.includes('--check') ? 'stale' : 'updated'}`
  );
}
