const fs = require('node:fs');
const path = require('node:path');

const REGEX_AFTER_KEYWORD =
  /(?:^|[^\w$])(?:return|typeof|instanceof|case|do|else|in|of|new|delete|void|throw|yield|await)$/;

function regexAllowed(code) {
  const trimmed = code.trimEnd();
  if (!trimmed) return true;
  if (REGEX_AFTER_KEYWORD.test(trimmed)) return true;
  return /[(,=:[!&|?{};+\-*%<>~^]$/.test(trimmed);
}

// Blanks comments, string/regex literals and template text so that only
// executable code remains; template `${}` expressions stay as code.
function codeOnly(source) {
  let out = '';
  let i = 0;
  const templateDepth = [];
  let braceDepth = 0;
  while (i < source.length) {
    const ch = source[i];
    const next = source[i + 1];
    if (ch === '/' && next === '/') {
      while (i < source.length && source[i] !== '\n') i++;
      out += ' ';
      continue;
    }
    if (ch === '/' && next === '*') {
      const end = source.indexOf('*/', i + 2);
      i = end === -1 ? source.length : end + 2;
      out += ' ';
      continue;
    }
    if (ch === '"' || ch === "'") {
      i++;
      while (i < source.length && source[i] !== ch && source[i] !== '\n') {
        i += source[i] === '\\' ? 2 : 1;
      }
      i++;
      out += ' 0 ';
      continue;
    }
    if (ch === '`' || (ch === '}' && templateDepth.at(-1) === braceDepth)) {
      const resumed = ch === '}';
      if (resumed) templateDepth.pop();
      i++;
      let expression = false;
      while (i < source.length) {
        if (source[i] === '\\') {
          i += 2;
        } else if (source[i] === '`') {
          i++;
          break;
        } else if (source[i] === '$' && source[i + 1] === '{') {
          i += 2;
          templateDepth.push(braceDepth);
          expression = true;
          break;
        } else {
          i++;
        }
      }
      out += `${resumed ? ' ) + ' : ' '}0${expression ? ' + ( ' : ' '}`;
      continue;
    }
    if (ch === '/' && regexAllowed(out)) {
      i++;
      let inClass = false;
      while (i < source.length && source[i] !== '\n') {
        if (source[i] === '\\') {
          i += 2;
          continue;
        }
        if (source[i] === '[') inClass = true;
        else if (source[i] === ']') inClass = false;
        else if (source[i] === '/' && !inClass) break;
        i++;
      }
      i++;
      while (/[a-z]/i.test(source[i] ?? '')) i++;
      out += ' 0 ';
      continue;
    }
    if (ch === '{') braceDepth++;
    if (ch === '}') braceDepth--;
    out += ch;
    i++;
  }
  return out;
}

const EXTENSIONS = ['', '.ts', '.tsx', '.js', '.mjs', '/index.ts', '/index.js'];

function firstExisting(root, candidate) {
  for (const extension of EXTENSIONS) {
    const file = candidate + extension;
    const absolute = path.join(root, file);
    if (fs.existsSync(absolute) && fs.statSync(absolute).isFile()) return file;
  }
  return null;
}

function packageExportTarget(root, packageDir, subpath) {
  try {
    const manifest = JSON.parse(
      fs.readFileSync(path.join(root, packageDir, 'package.json'), 'utf8')
    );
    const entry = manifest.exports?.[`./${subpath}`];
    const target =
      typeof entry === 'string' ? entry : (entry?.import ?? entry?.default);
    if (typeof target === 'string') {
      return firstExisting(root, path.posix.join(packageDir, target));
    }
  } catch {
    return null;
  }
  return null;
}

// Resolves a route module specifier to a repository-relative file, or null.
function resolveModule(root, fromFile, specifier) {
  if (specifier.startsWith('.')) {
    return firstExisting(
      root,
      path.posix.join(path.posix.dirname(fromFile), specifier)
    );
  }
  if (specifier.startsWith('@/')) {
    const app = fromFile.split('/').slice(0, 3).join('/');
    return firstExisting(root, path.posix.join(app, specifier.slice(2)));
  }
  const scoped = /^@tuturuuu\/([^/]+)\/(.+)$/.exec(specifier);
  if (!scoped) return null;
  const packageDir = `packages/${scoped[1]}`;
  return (
    packageExportTarget(root, packageDir, scoped[2]) ??
    firstExisting(root, path.posix.join(packageDir, 'src', scoped[2]))
  );
}

const REEXPORT = /export\s*(?:\*|\{[^}]*\})\s*from\s*(['"])([^'"]+)\1\s*;?/g;

// Returns the modules a pure re-export route delegates to, or null when the
// file defines any code of its own.
function reexportTargets(source) {
  const specifiers = [...source.matchAll(REEXPORT)].map((match) => match[2]);
  if (!specifiers.length) return null;
  const remainder = codeOnly(source.replace(REEXPORT, ' ')).trim();
  return remainder ? null : specifiers;
}

const WRAPPER_HEADER =
  '// @generated by scripts/generate-web-api-route-wrappers.js. Do not edit manually.';
const LEGACY_ROUTE_PATH =
  "@\\/legacy-api-routes\\/(?:(?!\\.\\.?(?:\\/|'))[^'\\/]+\\/)+route";
const LEGACY_GUARD_PATH =
  "@\\/legacy-api-routes\\/(?:(?!\\.\\.?(?:\\/|'))[^'\\/]+\\/)+route-guard";
const SCANNED_LEGACY_ROUTE_FILE =
  /^apps\/web\/src\/legacy-api-routes\/.+\/route\.[cm]?[jt]sx?$/;
const WRAPPER_ROUTE_IMPORT = new RegExp(
  `^import \\* as (route\\d+) from '(${LEGACY_ROUTE_PATH})';$`,
  'gm'
);
const WRAPPER_HELPER_IMPORT =
  /^import \{\s*createWorkspaceRouteHandlers\s*\} from '@\/legacy-api-routes\/workspace-route-group';$/gm;
const WRAPPER_GUARD_IMPORT = new RegExp(
  `^import \\{\\s*guard\\s*\\} from '${LEGACY_GUARD_PATH}';$`,
  'gm'
);
const HTTP_METHODS = new Set([
  'GET',
  'HEAD',
  'POST',
  'PUT',
  'PATCH',
  'DELETE',
  'OPTIONS',
]);
const WRAPPER_EXPORT_PREFIX =
  /^export const \{([A-Z,\s]+)\}\s*=\s*createWorkspaceRouteHandlers\(\s*\[/;

const LEGACY_ROUTE_IMPORT = new RegExp(
  `^import \\* as legacyRoute from '(${LEGACY_ROUTE_PATH})';$`,
  'gm'
);
const LEGACY_HEAD_IMPORT =
  /^import \{\s*(?:createLegacyGetHandler|createLegacyHeadHandler)(?:\s*,\s*(?:createLegacyGetHandler|createLegacyHeadHandler))*\s*,?\s*\} from '@\/legacy-api-routes\/head';$/gm;
const LEGACY_EXPORT_LINE =
  /^export const (?:GET = createLegacyGetHandler\(legacyRoute\.GET\)|HEAD = createLegacyHeadHandler\(GET\)|(GET|HEAD|POST|PUT|PATCH|DELETE|OPTIONS) = legacyRoute\.\1);$/;

function parseWrapperExport(remainder) {
  const prefixMatch = WRAPPER_EXPORT_PREFIX.exec(remainder);
  if (!prefixMatch) return null;
  const rawMethods = prefixMatch[1].trim();
  if (!rawMethods) return null;
  const methodTokens = rawMethods.split(',').map((token) => token.trim());
  if (methodTokens.at(-1) === '') methodTokens.pop();
  if (
    methodTokens.length === 0 ||
    !methodTokens.every((method) => HTTP_METHODS.has(method))
  )
    return null;

  const closeBracket = remainder.lastIndexOf(']');
  if (closeBracket < prefixMatch[0].length) return null;
  let suffix = remainder.slice(closeBracket + 1).trim();
  if (suffix.endsWith(';')) suffix = suffix.slice(0, -1).trim();
  if (!suffix.endsWith(')')) return null;
  suffix = suffix.slice(0, -1).trim();
  if (suffix.endsWith(',')) suffix = suffix.slice(0, -1).trim();
  if (suffix !== '' && !/^,\s*guard$/.test(suffix)) return null;
  return remainder.slice(prefixMatch[0].length, closeBracket);
}

function skipWs(text, index) {
  let pos = index;
  while (pos < text.length && /\s/.test(text[pos])) pos += 1;
  return pos;
}

function readIdent(text, index) {
  let pos = index;
  while (pos < text.length && /[A-Za-z0-9_]/.test(text[pos])) pos += 1;
  return pos;
}

function isValidDispatchTable(tableBody, importedRoutes) {
  let pos = skipWs(tableBody, 0);
  let entryCount = 0;

  while (pos < tableBody.length) {
    if (tableBody[pos] !== '[') return false;
    pos = skipWs(tableBody, pos + 1);

    // Parse segment array: [ 'seg1', 'seg2', ... ]
    if (tableBody[pos] !== '[') return false;
    pos = skipWs(tableBody, pos + 1);
    while (pos < tableBody.length && tableBody[pos] !== ']') {
      if (tableBody[pos] !== "'") return false;
      pos += 1;
      while (pos < tableBody.length && tableBody[pos] !== "'") {
        if (
          tableBody[pos] === '\\' ||
          tableBody[pos] === '\n' ||
          tableBody[pos] === '\r'
        )
          return false;
        pos += 1;
      }
      if (tableBody[pos] !== "'") return false;
      pos = skipWs(tableBody, pos + 1);
      if (tableBody[pos] === ',') {
        pos = skipWs(tableBody, pos + 1);
      } else if (tableBody[pos] !== ']') {
        return false;
      }
    }
    if (tableBody[pos] !== ']') return false;
    pos = skipWs(tableBody, pos + 1);
    if (tableBody[pos] !== ',') return false;
    pos = skipWs(tableBody, pos + 1);

    // Parse handler map: { GET: route0.GET, ... }
    if (tableBody[pos] !== '{') return false;
    pos = skipWs(tableBody, pos + 1);
    let handlerCount = 0;
    while (pos < tableBody.length && tableBody[pos] !== '}') {
      const keyEnd = readIdent(tableBody, pos);
      const key = tableBody.slice(pos, keyEnd);
      if (!HTTP_METHODS.has(key)) return false;
      pos = skipWs(tableBody, keyEnd);
      if (tableBody[pos] !== ':') return false;
      pos = skipWs(tableBody, pos + 1);

      const routeEnd = readIdent(tableBody, pos);
      const routeVar = tableBody.slice(pos, routeEnd);
      if (!/^route\d+$/.test(routeVar) || !importedRoutes.has(routeVar))
        return false;
      pos = routeEnd;
      if (tableBody[pos] !== '.') return false;
      pos += 1;

      const methodEnd = readIdent(tableBody, pos);
      const method = tableBody.slice(pos, methodEnd);
      if (method !== key) return false;
      handlerCount += 1;
      pos = skipWs(tableBody, methodEnd);

      if (tableBody[pos] === ',') {
        pos = skipWs(tableBody, pos + 1);
      } else if (tableBody[pos] !== '}') {
        return false;
      }
    }
    if (tableBody[pos] !== '}' || handlerCount === 0) return false;
    pos = skipWs(tableBody, pos + 1);

    if (tableBody[pos] === ',') {
      pos = skipWs(tableBody, pos + 1);
    }
    if (tableBody[pos] !== ']') return false;
    pos = skipWs(tableBody, pos + 1);
    entryCount += 1;

    if (tableBody[pos] === ',') {
      pos = skipWs(tableBody, pos + 1);
    } else if (pos < tableBody.length) {
      return false;
    }
  }

  return entryCount > 0;
}

function resolvesToScannedLegacyRoute(root, file, specifier) {
  const target = resolveModule(root, file, specifier);
  return Boolean(target && SCANNED_LEGACY_ROUTE_FILE.test(target));
}

// A generated wrapper under apps/web/src/app/api/ only dispatches to scanned
// legacy route files under apps/web/src/legacy-api-routes/**/route.*. Every
// token outside the two exact generator templates and every target that does
// not resolve to a scanned legacy route file is rejected.
function isGeneratedLegacyWrapper(root, file, source) {
  if (!file.startsWith('apps/web/src/app/api/')) return false;
  if (!source.startsWith(WRAPPER_HEADER)) return false;
  const body = source.slice(WRAPPER_HEADER.length);

  // Template 1: workspace route-group wrapper (createWorkspaceRouteHandlers)
  const routeImports = [...body.matchAll(WRAPPER_ROUTE_IMPORT)];
  const helperImports = [...body.matchAll(WRAPPER_HELPER_IMPORT)];
  if (routeImports.length > 0 && helperImports.length === 1) {
    if (
      !routeImports.every((match) =>
        resolvesToScannedLegacyRoute(root, file, match[2])
      )
    )
      return false;
    const importedRoutes = new Set(routeImports.map((match) => match[1]));
    const remainder = body
      .replace(WRAPPER_ROUTE_IMPORT, '')
      .replace(WRAPPER_HELPER_IMPORT, '')
      .replace(WRAPPER_GUARD_IMPORT, '')
      .trim();
    const tableBody = parseWrapperExport(remainder);
    if (tableBody === null) return false;
    return isValidDispatchTable(tableBody, importedRoutes);
  }

  // Template 2: single-route legacy wrapper (legacyRoute.*)
  const legacyImports = [...body.matchAll(LEGACY_ROUTE_IMPORT)];
  if (legacyImports.length === 1) {
    if (!resolvesToScannedLegacyRoute(root, file, legacyImports[0][1]))
      return false;
    const remainder = body
      .replace(LEGACY_ROUTE_IMPORT, '')
      .replace(LEGACY_HEAD_IMPORT, '')
      .trim();
    const lines = remainder
      .split('\n')
      .map((line) => line.trim())
      .filter(Boolean);
    return (
      lines.length > 0 && lines.every((line) => LEGACY_EXPORT_LINE.test(line))
    );
  }

  return false;
}

module.exports = {
  codeOnly,
  isGeneratedLegacyWrapper,
  reexportTargets,
  resolveModule,
};
