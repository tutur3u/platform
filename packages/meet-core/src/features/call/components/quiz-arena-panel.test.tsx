import {
  QueryClient,
  QueryClientProvider,
  useQuery,
} from '@tanstack/react-query';
import {
  cleanup,
  fireEvent,
  render,
  screen,
  waitFor,
} from '@testing-library/react';
import type {
  ProjectedArenaTile,
  QuizArenaFullView,
} from '@tuturuuu/realtime/meet/room-quiz-arena';
import { NextIntlClientProvider } from 'next-intl';
import { afterEach, expect, it, vi } from 'vitest';
import en from '../../../../../../apps/meet/messages/en.json';
import viMessages from '../../../../../../apps/meet/messages/vi.json';
import type { QuizArenaClientView } from '../lib/quiz-arena-client';
import { QuizArenaControl, QuizArenaPanel } from './quiz-arena-panel';

const send = vi.hoisted(() => vi.fn());
vi.mock('../lib/quiz-arena-client', () => ({
  sendQuizArenaAction: send,
  quizArenaKey: () => ['arena'],
  notifyQuizArenaMutation: () => {},
  quizArenaExportUrl: (_meeting: string, format: string) =>
    `/arena?format=${format}`,
}));
vi.mock('../lib/quiz-arena-sfx', () => ({
  playBuzzCue: vi.fn(),
  playCorrectCue: vi.fn(),
  playWrongCue: vi.fn(),
  playFinalRoundCue: vi.fn(),
}));
vi.mock('./control-bar', () => ({
  ControlButton: ({
    label,
    onClick,
  }: {
    label: string;
    onClick: () => void;
  }) => (
    <button type="button" onClick={onClick}>
      {label}
    </button>
  ),
}));

const uuid = (n: number) =>
  `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const tile = (
  n: number,
  category: number,
  tier: number,
  extra: Partial<ProjectedArenaTile> = {}
): ProjectedArenaTile => ({
  id: uuid(100 + n),
  categoryIndex: category,
  tierIndex: tier,
  points: (tier + 1) * 100,
  isBonusWager: false,
  isFinal: false,
  status: 'available',
  openedAt: null,
  timeLimitSec: 30,
  question: null,
  reveal: null,
  answerCount: 0,
  wagerCount: 0,
  wageredTeamIds: [],
  buzzQueue: [],
  myAnswer: null,
  myWager: null,
  myResult: null,
  results: null,
  ...extra,
});

const base = (
  overrides: Partial<QuizArenaFullView['meta']> = {},
  tiles = [tile(1, 0, 0), tile(2, 1, 0), tile(3, 0, 1), tile(4, 1, 1)]
): QuizArenaFullView => ({
  kind: 'full',
  epoch: 'epoch',
  seq: 4,
  canManage: false,
  meta: {
    title: 'Lecture 04 review',
    source: 'mira',
    pickedBy: null,
    categories: ['Recursion', 'Big-O'],
    finalCategory: 'Recursion',
    tierPoints: [100, 200],
    answerMode: 'buzz_in',
    playMode: 'teams',
    speedBonus: false,
    wrongAnswerPenalty: 'none',
    phase: 'board',
    activeTileId: null,
    buzzersLocked: false,
    playedRounds: 0,
    ...overrides,
  },
  tiles,
  finalTile: null,
  players: Array.from({ length: 50 }, (_, i) => ({
    userId: uuid(i + 1),
    displayName: `Player ${i + 1}`,
    teamId: uuid(900 + (i % 2)),
    score: (50 - i) * 10,
    lastDelta: i === 0 ? 100 : 0,
    participatedRounds: 1,
    attendanceCredited: i < 10,
  })),
  teams: [
    {
      id: uuid(900),
      name: 'Teal',
      score: 700,
      lastDelta: 100,
      memberCount: 25,
    },
    { id: uuid(901), name: 'Blue', score: 500, lastDelta: 0, memberCount: 25 },
  ],
});

function renderPanel(
  data: QuizArenaClientView,
  locale: 'en' | 'vi' = 'en',
  self = uuid(1)
) {
  const client = new QueryClient();
  const onClose = vi.fn();
  function Fixture() {
    const query = useQuery({
      queryKey: ['arena'],
      queryFn: () => data,
      initialData: data,
    });
    return (
      <>
        <QuizArenaControl query={query} open onClick={onClose} />
        <QuizArenaPanel
          accountId={self}
          meetingId="meeting"
          query={query}
          onClose={onClose}
        />
      </>
    );
  }
  render(
    <QueryClientProvider client={client}>
      <NextIntlClientProvider
        locale={locale}
        messages={locale === 'vi' ? viMessages : en}
        timeZone="UTC"
      >
        <Fixture />
      </NextIntlClientProvider>
    </QueryClientProvider>
  );
  return { onClose };
}

afterEach(() => {
  cleanup();
  send.mockReset();
});

it('renders the original Quiz Arena name in both languages with Mira attribution', () => {
  renderPanel(base(), 'vi');
  expect(screen.getAllByText('Đấu trường kiến thức').length).toBeGreaterThan(0);
  expect(screen.getByText('Do Mira tạo')).toBeTruthy();
  cleanup();
  renderPanel(base());
  expect(screen.getByRole('heading', { name: 'Quiz Arena' })).toBeTruthy();
  expect(screen.getByText('Generated by Mira')).toBeTruthy();
  expect(document.body.textContent).not.toMatch(/jeopardy|what is/iu);
  expect(document.body.textContent).not.toMatch(/\p{Extended_Pictographic}/u);
});

it('keeps the board read-only for players and lets the host pick a tile', async () => {
  renderPanel(base());
  const tileButton = screen.getByRole('button', {
    name: 'Recursion, 100 points',
  });
  expect((tileButton as HTMLButtonElement).disabled).toBe(true);
  cleanup();
  send.mockResolvedValue({ ok: true, seq: 5 });
  renderPanel({ ...base(), canManage: true });
  fireEvent.click(screen.getByRole('button', { name: 'Big-O, 200 points' }));
  await waitFor(() =>
    expect(send).toHaveBeenCalledWith('meeting', {
      action: 'pickTile',
      tileId: uuid(104),
    })
  );
});

it('shows the buzzer, Mira’s live pick and the buzz queue for an active buzz-in tile', async () => {
  const active = tile(1, 0, 0, {
    status: 'active',
    openedAt: Date.now(),
    question: {
      type: 'single_choice',
      question: 'Base case of factorial?',
      options: [
        { id: uuid(201), label: 'n = 0' },
        { id: uuid(202), label: 'n = 10' },
      ],
    },
    buzzQueue: [
      {
        userId: uuid(2),
        displayName: 'Player 2',
        buzzedAt: Date.now() + 420,
        status: 'answering',
      },
    ],
  });
  send.mockResolvedValue({ ok: true, seq: 6 });
  renderPanel(
    base({ phase: 'question', activeTileId: active.id, pickedBy: 'mira' }, [
      active,
      tile(2, 1, 0),
    ])
  );
  expect(screen.getByText('Mira picked this tile')).toBeTruthy();
  expect(screen.getAllByText('Mira • Live').length).toBeGreaterThan(0);
  expect(screen.getByText('Base case of factorial?')).toBeTruthy();
  expect(screen.getByText('0.42s')).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: /BUZZ/u }));
  await waitFor(() =>
    expect(send).toHaveBeenCalledWith('meeting', {
      action: 'buzz',
      tileId: active.id,
    })
  );
});

it('asks for a team wager before showing a bonus question', async () => {
  const bonus = tile(3, 0, 1, {
    status: 'active',
    openedAt: Date.now(),
    isBonusWager: true,
  });
  send.mockResolvedValue({ ok: true, seq: 7 });
  renderPanel(
    base(
      { phase: 'question', activeTileId: bonus.id, answerMode: 'all_answer' },
      [bonus]
    )
  );
  expect(screen.getByText('Bonus tile! Teal wagers')).toBeTruthy();
  expect(
    screen.getByText('The question appears after the wager is locked.')
  ).toBeTruthy();
  expect(screen.getByText('Max 700 (team score)')).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: 'Lock our wager' }));
  await waitFor(() =>
    expect(send).toHaveBeenCalledWith('meeting', {
      action: 'wager',
      tileId: bonus.id,
      amount: 200,
    })
  );
});

it('ranks 50 players and teams with attendance credit', () => {
  renderPanel(base());
  expect(
    screen.getByRole('tab', { name: 'Teams', selected: true })
  ).toBeTruthy();
  expect(screen.getByText('Teal · 25')).toBeTruthy();
  fireEvent.click(screen.getByRole('tab', { name: 'Individual' }));
  expect(screen.getAllByRole('listitem').length).toBeGreaterThanOrEqual(50);
  expect(screen.getByText('You · Player 1')).toBeTruthy();
  expect(screen.getAllByLabelText('Attendance credit')).toHaveLength(10);
});

it('shows the builder to hosts on an empty arena and offers the starter board after a Mira fallback', async () => {
  send
    .mockResolvedValueOnce({ ok: false, fallback: true })
    .mockResolvedValueOnce({ ok: true, seq: 1, fallback: true });
  renderPanel({ kind: 'empty', canManage: true });
  expect(screen.getByLabelText('Subject')).toBeTruthy();
  expect(screen.getByLabelText('Grade')).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: 'Generate with Mira' }));
  await waitFor(() =>
    expect(screen.getByText("Mira can't build a board right now.")).toBeTruthy()
  );
  expect(send.mock.calls[0]?.[1]).toMatchObject({
    action: 'mira_generate_board',
    request: { subject: 'general', grade: '10' },
  });
  fireEvent.click(screen.getByRole('button', { name: 'Use a starter board' }));
  await waitFor(() =>
    expect(send.mock.calls[1]?.[1]).toMatchObject({ useStarterFallback: true })
  );
  cleanup();
  renderPanel({ kind: 'empty', canManage: false });
  expect(screen.getByText("The host hasn't set up a board yet.")).toBeTruthy();
});
